"""Rebuild the article's exact tables from the bundled rational certificates."""
from fractions import Fraction as Q
from pathlib import Path
import json,math
ROOT=Path(__file__).resolve().parent

def remainder(a,b):
    a=list(a)
    while len(a)>=len(b):
        c=a[-1]/b[-1];n=len(a)-len(b)
        for i,x in enumerate(b):a[n+i]-=c*x
        while len(a)>1 and a[-1]==0:a.pop()
    return a

def texq(q):
    q=Q(q)
    return str(q.numerator) if q.denominator==1 else ('-' if q<0 else '')+r'\frac{'+str(abs(q.numerator))+'}{'+str(q.denominator)+'}'

def poly(cs):
    out=''
    for i,c in reversed(list(enumerate(cs))):
        c=Q(c)
        if not c:continue
        sign='-' if c<0 else ('+' if out else '')
        mag='' if abs(c)==1 and i else texq(abs(c))
        out+=sign+mag+('X' if i==1 else ('X^{'+str(i)+'}' if i else ''))
    return out or '0'

def enclosing(b,scale=100):
    lo,hi=map(Q,b)
    # Broaden by one unit in the last displayed place for strict containment.
    a=lo.numerator*scale//lo.denominator-1
    z=-((-hi.numerator*scale)//hi.denominator)+1
    return [str(Q(a,scale)),str(Q(z,scale))]

def main():
    cert=json.loads((ROOT/'producer/output/certificate.json').read_text())['cases']
    rec=json.loads((ROOT/'producer/output/certificate-check.json').read_text())['cases']
    ind=json.loads((ROOT/'independent/source-certificate-check.json').read_text())['cases']
    rows=[];jets=[];bounds=[];coordinates=[];equations=[]
    for r,p,c in zip(cert,rec,ind):
        assert r['k']==p['k']==c['k']
        f=list(map(Q,r['polynomial_ascending']));g=remainder(list(map(Q,r['gamma_ascending'])),f)
        den=math.lcm(*(z.denominator for z in g));num=[int(z*den) for z in g]
        rho=enclosing(r['root_interval'],10**13)
        dj=enclosing(c['alternate_full_jacobian_interval']);gap=enclosing(c['fifth_difference_interval'])
        assert Q(dj[1])<0 and Q(gap[1])<0
        row=dict(k=r['k'],root_polynomial_ascending=r['polynomial_ascending'],gamma_numerator_ascending=num,gamma_denominator=den,
            displayed_root_enclosure=rho,true_jets_0_to_4=r['jets_0_to_5'][:5],true_J4_determinant=p['true_J4_jacobian_determinant'][0],alternate_J4_determinant_enclosure=dj,fifth_difference_enclosure=gap)
        assert c['sturm_count_in_0_1']==1
        point_bounds={name:enclosing(p['positive_intervals'][name],1000) for name in ['alpha','gamma','S','Z','R']}
        for name,enc in point_bounds.items():
            lo,hi=map(Q,p['positive_intervals'][name]);assert 0<Q(enc[0])<lo<=hi<Q(enc[1])
        row['alternate_coordinate_enclosures']=point_bounds
        row['sturm_count_in_0_1']=c['sturm_count_in_0_1']
        rows.append(row)
        k=texq(r['k'])
        jets.append('$'+k+'$ & $'+ '$ & $'.join(texq(z) for z in r['jets_0_to_5'][2:5])+'$ & $'+texq(row['true_J4_determinant'])+r'$ \\')
        bounds.append('$'+k+'$ & $('+', '.join(f'{float(Q(z)):.13f}' for z in rho)+')$ & $('+', '.join(f'{float(Q(z)):.2f}' for z in dj)+')$ & $('+', '.join(f'{float(Q(z)):.2f}' for z in gap)+r')$ \\')
        coordinates.append('$'+k+'$ & '+ ' & '.join('$('+', '.join(f'{float(Q(z)):.3f}' for z in point_bounds[name])+')$' for name in ['alpha','gamma','S','Z','R'])+r' \\')
        equations.append('For $k='+k+'$,\n'+r'\[\begin{aligned}'+'\n'+r'f_k(X)&='+poly(f)+r',\\'+'\n'+r'g_k(X)&=\frac{'+poly(num)+'}{'+str(den)+'}.'+'\n'+r'\end{aligned}\]'+'\n')
    data=dict(description='Exact transcription of main certificate data; interval endpoints are rational and outward-rounded, not fitted roots.',cases=rows)
    (ROOT/'article-cases.json').write_text(json.dumps(data,indent=2)+'\n')
    (ROOT/'certificate-tables.tex').write_text(r'''% Generated by build_tables.py from exact bundled certificates.
\newcommand{\MainJetRows}{
'''+ '\n'.join(jets)+'\n}\n'+r'\newcommand{\MainBoundRows}{'+'\n'+'\n'.join(bounds)+'\n}\n'+r'\newcommand{\MainCoordinateRows}{'+'\n'+'\n'.join(coordinates)+'\n}\n'+r'\newcommand{\CertificatePolynomials}{'+'\n'+'\n'.join(equations)+'}\n')
    print('Rebuilt three exact article cases and TeX tables')
if __name__=='__main__':main()
